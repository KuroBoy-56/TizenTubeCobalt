#!/usr/bin/env python3
"""Puts dist/userScript.js inside the APK.

Writes third_party/blink/renderer/core/dom/youtube_mod_user_script.h, the script that
document.cc runs when YouTube loads, with the login images (dist/login/) inside it as data:
URIs. The APK then downloads nothing from GitHub or jsDelivr: a change to dist/userScript.js
only reaches the TVs with a new APK.

The build runs this before compiling (.github/actions/build/action.yaml), so the header always
matches dist/userScript.js. Locally:

  python3 tools/ytmod/embed_user_script.py            # write the header
  python3 tools/ytmod/embed_user_script.py --check    # fail if the header is out of date
  python3 tools/ytmod/embed_user_script.py --js out.js  # also write the script as the APK runs it
"""

import argparse
import base64
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCRIPT = os.path.join(ROOT, 'dist', 'userScript.js')
LOGIN_DIR = os.path.join(ROOT, 'dist', 'login')
HEADER = os.path.join(ROOT, 'third_party', 'blink', 'renderer', 'core', 'dom',
                      'youtube_mod_user_script.h')
MARKER = 'var EMBEDDED_ASSETS = null; // @ytmod-embedded-assets'
ASSETS = (('bg', 'login_bg.jpg', 'image/jpeg'), ('logo', 'logo_login.png', 'image/png'))


def data_uri(name, mime):
  with open(os.path.join(LOGIN_DIR, name), 'rb') as f:
    return 'data:%s;base64,%s' % (mime, base64.b64encode(f.read()).decode('ascii'))


def embedded_script():
  with open(SCRIPT, encoding='utf-8') as f:
    js = f.read()
  if js.count(MARKER) != 1:
    sys.exit('dist/userScript.js must contain this line exactly once: ' + MARKER)
  assets = ', '.join('%s: "%s"' % (key, data_uri(name, mime)) for key, name, mime in ASSETS)
  return js.replace(MARKER, 'var EMBEDDED_ASSETS = {%s};' % assets)


def header(js):
  data = js.encode('utf-8')
  out = [
      '// Generated by tools/ytmod/embed_user_script.py from dist/userScript.js and\n',
      '// dist/login/. Do not edit: change those and run the script.\n',
      '#ifndef THIRD_PARTY_BLINK_RENDERER_CORE_DOM_YOUTUBE_MOD_USER_SCRIPT_H_\n',
      '#define THIRD_PARTY_BLINK_RENDERER_CORE_DOM_YOUTUBE_MOD_USER_SCRIPT_H_\n\n',
      '#include <cstdint>\n\n',
      'namespace blink {\n\n',
      '// UTF-8 text of the script (no terminating 0).\n',
      'inline constexpr uint8_t kYouTubeModUserScript[%d] = {\n' % len(data),
  ]
  for i in range(0, len(data), 24):
    out.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',\n')
  out.append('};\n\n')
  out.append('}  // namespace blink\n\n')
  out.append('#endif  // THIRD_PARTY_BLINK_RENDERER_CORE_DOM_YOUTUBE_MOD_USER_SCRIPT_H_\n')
  return ''.join(out)


def main():
  parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  parser.add_argument('--check', action='store_true', help='fail if the header is out of date')
  parser.add_argument('--js', help='also write the embedded script to this file')
  args = parser.parse_args()

  js = embedded_script()
  text = header(js)
  if args.js:
    with open(args.js, 'w', encoding='utf-8') as f:
      f.write(js)
  if args.check:
    current = open(HEADER, encoding='utf-8').read() if os.path.exists(HEADER) else ''
    if current != text:
      sys.exit('%s is out of date: run tools/ytmod/embed_user_script.py' % HEADER)
    print('up to date: %s' % os.path.relpath(HEADER, ROOT))
    return
  with open(HEADER, 'w', encoding='utf-8') as f:
    f.write(text)
  print('wrote %s (%d bytes of script)' % (os.path.relpath(HEADER, ROOT), len(js.encode('utf-8'))))


if __name__ == '__main__':
  main()
